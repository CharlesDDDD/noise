"""Prepare the fixed data of Noise: the Dust paper's 10M-token FineWeb training set and its validation set.

    python utils/prepare_data.py            # writes data/train.pt and data/val.pt, then checks their hashes
    python utils/prepare_data.py --verify   # only checks existing files

The split is exactly the one in https://github.com/qlabs-eng/dust (`train_10M.pt` and `val.pt`):
FineWeb `sample-10BT` in stream order, the first 200,000 documents skipped (they trained the BPE-4096
tokenizer), then a ~20.5M-token training pool whose first 4,880 rows are the training set, then the
validation documents. Rows are 2,049 tokens (2,048 predictions), documents are joined with <|endoftext|>.
Do not edit this file; every submission trains on train.pt and is scored on val.pt.
"""
import argparse
import hashlib
import json
from pathlib import Path

import torch

SEQ = 2049
TRAIN_ROWS = 4880        # 9,994,240 prediction tokens
VAL_ROWS = 544           # 1,114,112 prediction tokens
SKIP_DOCS = 200_000
POOL_TOKENS = 20_500_000
VAL_POOL_TOKENS = 1_150_000

# sha256 of the int32 little-endian token bytes (independent of the torch.save container)
EXPECTED = {
    'train.pt': '36ccb57eba6f5474b18acf99edd4a4793187260f7da7cc7053322cce59154bde',
    'val.pt': '5fdb9242ce8ab83e519ab5dd5cf8d64f4d8a99f6e74c137f4ca0f723da5f7437',
}
TOKENIZER = Path(__file__).resolve().parents[3] / 'tokenizer' / 'tokenizer.json'  # the repository's
TOKENIZER_SHA256 = 'a15168ae52f4a1b1c80b270a5e18a2ce3e038b5e3772a1ad3982044602da0ae7'


def token_hash(rows):
    return hashlib.sha256(rows.to(torch.int32).contiguous().numpy().tobytes()).hexdigest()


def load_rows(path, rows):
    """Load a fixed split as int64 [rows, 2049]; refuses anything that is not the pinned data."""
    data = torch.load(path, map_location='cpu', weights_only=True)
    if not isinstance(data, torch.Tensor) or tuple(data.shape) != (rows, SEQ):
        raise ValueError(f'{path}: expected a [{rows}, {SEQ}] token tensor')
    expected = EXPECTED[Path(path).name]
    if expected is not None and token_hash(data) != expected:
        raise ValueError(f'{path}: token hash mismatch; rerun utils/prepare_data.py')
    return data.long()


def encode_split(documents, tokenizer, min_tokens):
    tokens = []
    end = tokenizer.token_to_id('<|endoftext|>')
    while len(tokens) < min_tokens:
        tokens.append(end)
        tokens.extend(tokenizer.encode(next(documents)['text']).ids)
    usable = len(tokens) // SEQ * SEQ
    return torch.tensor(tokens[:usable], dtype=torch.int32).view(-1, SEQ)


def verify(out):
    ok = True
    for name, rows in (('train.pt', TRAIN_ROWS), ('val.pt', VAL_ROWS)):
        data = torch.load(out / name, map_location='cpu', weights_only=True)
        digest = token_hash(data)
        expected = EXPECTED[name]
        status = 'unpinned' if expected is None else ('OK' if digest == expected else 'MISMATCH')
        ok &= status != 'MISMATCH' and tuple(data.shape) == (rows, SEQ)
        print(f'{out / name}: {tuple(data.shape)} sha256 {digest} [{status}]', flush=True)
    if not ok:
        raise SystemExit('data does not match the pinned hashes')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--output', type=Path, default=Path('data'))
    parser.add_argument('--parquet', nargs='+', help='Optional local FineWeb sample-10BT shards, in stream order.')
    parser.add_argument('--verify', action='store_true', help='Only check existing files.')
    args = parser.parse_args()
    if args.verify:
        return verify(args.output)

    from datasets import load_dataset
    from tokenizers import Tokenizer

    if hashlib.sha256(TOKENIZER.read_bytes()).hexdigest() != TOKENIZER_SHA256:
        raise SystemExit(f'{TOKENIZER} is not the fixed BPE-4096 tokenizer')
    tokenizer = Tokenizer.from_file(str(TOKENIZER))
    if args.parquet:
        corpus = load_dataset('parquet', data_files=args.parquet, split='train', streaming=True)
    else:
        corpus = load_dataset('HuggingFaceFW/fineweb', name='sample-10BT', split='train', streaming=True)
    documents = iter(corpus)
    for _ in range(SKIP_DOCS):
        next(documents)
    # The validation documents follow the whole ~20.5M-token pool the paper drew its budgets from.
    train = encode_split(documents, tokenizer, POOL_TOKENS)[:TRAIN_ROWS].clone()
    val = encode_split(documents, tokenizer, VAL_POOL_TOKENS)[:VAL_ROWS].clone()

    args.output.mkdir(parents=True, exist_ok=True)
    manifest = dict(corpus='HuggingFaceFW/fineweb', subset='sample-10BT', skipped_documents=SKIP_DOCS,
                    tokenizer_sha256=TOKENIZER_SHA256, files={})
    for name, rows in (('train.pt', train), ('val.pt', val)):
        torch.save(rows, args.output / name)
        manifest['files'][name] = dict(rows=len(rows), prediction_tokens=len(rows) * (SEQ - 1),
                                       token_sha256=token_hash(rows))
    (args.output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    verify(args.output)


if __name__ == '__main__':
    main()
