"""The speedrun's score: mean next-token cross-entropy of final weights on the fixed validation set.

    python utils/eval.py logs/val/final.pt
    torchrun --standalone --nproc_per_node=8 utils/eval.py logs/val/final.pt

Training scripts call evaluate() on their final weights; running this file on the saved checkpoint gives
the same number. The weights are loaded into a fresh copy of the fixed model, so a training script's own
forward never touches the score. Do not edit this file.
"""
import argparse
import json
import os
from pathlib import Path
import sys

import torch
from torch import distributed as dist

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils.model import GPT, GPTConfig
from utils.prepare_data import VAL_ROWS, load_rows


def load_model(state_dict, device):
    """The fixed architecture with these weights; a missing, extra or reshaped tensor is an error."""
    with torch.device('meta'):
        model = GPT(GPTConfig())
    model.to_empty(device=device)
    model.init_weights()  # rotary tables, and the bfloat16 storage of the embeddings
    model.load_state_dict(state_dict, strict=True)
    return model.eval().requires_grad_(False)


@torch.no_grad()
def evaluate(state_dict, data_dir='data', batch_size=16):
    """Mean loss over all 1,114,112 validation predictions. Under torchrun the rows are split across ranks."""
    rank, world = (dist.get_rank(), dist.get_world_size()) if dist.is_initialized() else (0, 1)
    device = torch.device('cuda', torch.cuda.current_device())
    model = load_model(state_dict, device)
    rows = load_rows(Path(data_dir) / 'val.pt', VAL_ROWS)[rank::world]
    total = torch.zeros(2, dtype=torch.float64, device=device)  # summed loss, predictions
    for batch in rows.split(batch_size):
        batch = batch.to(device)
        with torch.autocast('cuda', dtype=torch.bfloat16):
            loss = model(batch[:, :-1].contiguous(), batch[:, 1:].contiguous(), loss_reduction='sum')
        total[0] += loss.double()
        total[1] += batch[:, 1:].numel()
    if world > 1:
        dist.all_reduce(total)
    value = (total[0] / total[1]).item()
    if value != value:
        raise FloatingPointError('Non-finite validation loss')
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('checkpoint', type=Path, help='A state dict saved by a training script.')
    parser.add_argument('--data-dir', type=Path, default=Path('data'))
    args = parser.parse_args()
    if 'RANK' in os.environ:
        torch.cuda.set_device(int(os.environ['LOCAL_RANK']))
        dist.init_process_group('nccl')
    else:
        torch.cuda.set_device(0)
    state_dict = torch.load(args.checkpoint, map_location='cpu', weights_only=True)
    value = evaluate(state_dict, args.data_dir)
    if not dist.is_initialized() or dist.get_rank() == 0:
        print(json.dumps(dict(checkpoint=str(args.checkpoint), val_loss=value)), flush=True)
    if dist.is_initialized():
        dist.destroy_process_group()


if __name__ == '__main__':
    main()
